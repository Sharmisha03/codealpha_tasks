# 🤖 Task 3: Basic Chatbot

## 📌 Description
This project is a simple rule-based chatbot developed using Python.  
It interacts with the user by responding to common inputs such as greetings, questions, and daily conversation phrases.

---

## 🚀 Features
- Handles multiple user inputs (10–15 common phrases)
- Predefined intelligent responses
- Continuous conversation using loop
- Exit option using "bye"
- User-friendly interaction

---

## 🧠 Concepts Used
- Functions
- if-elif statements
- while loop
- input/output

---

## ▶️ How to Run
1. Open terminal or command prompt  
2. Navigate to project folder  
3. Run:

```
py task3_chatbot.py
```

---

## 🎮 Sample Interaction

```
You: hi
Bot: Hi! 👋 How can I help you today?

You: what are you doing
Bot: I'm here to assist you with your queries 🤖

You: tell me a joke
Bot: Why do programmers prefer dark mode? Because light attracts bugs! 😄

You: bye
Bot: Goodbye! 👋 Have a nice day!
```

